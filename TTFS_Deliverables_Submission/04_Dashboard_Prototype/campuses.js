document.addEventListener('DOMContentLoaded', () => {

  // 1. Render the HTML Grid
  const gridContainer = document.getElementById("campusGridContainer");
  if (gridContainer) {
    gridContainer.innerHTML = ""; // Clear existing
    projectCampuses.forEach(campus => {
      const isReady = campus.status === "Active Implementation" || campus.status === "Baseline Data Collection" || campus.status === "Pending Design Approval";
      const badgeClass = campus.status === "Active Implementation" ? "status-active" : "status-pending";
      const btnHtml = isReady ? `<button class="campus-action btn-select" data-id="${campus.id}">View Dashboard Models</button>` : `<button class="campus-action" style="background:#ccc; cursor:not-allowed;" disabled>Awaiting Implementation</button>`;

      const html = `
        <div class="campus-card">
          <div class="campus-header">
            <h2>${campus.name}</h2>
            <p>${campus.district}</p>
          </div>
          <div class="campus-body">
            <span class="status-badge ${badgeClass}">${campus.status}</span>
            <div class="metrics-mini">
              <div class="metric-mini-box">
                <div class="lbl">Baseline Canopy</div>
                <div class="val">${campus.canopy.baselinePercent}%</div>
              </div>
              <div class="metric-mini-box">
                <div class="lbl">2040 Shade Goal</div>
                <div class="val" style="color:#d84315;">${campus.canopy.targetPercent}%</div>
              </div>
            </div>
          </div>
          ${btnHtml}
        </div>
      `;
      gridContainer.insertAdjacentHTML('beforeend', html);
    });

    const selectBtns = document.querySelectorAll('.btn-select');
    selectBtns.forEach(btn => {
      btn.addEventListener('click', (e) => {
        const campusId = e.target.getAttribute('data-id');
        selectCampus(campusId);
      });
    });
  }

  // 2. Initialize Overview Map with ArcGIS
  require([
    "esri/Map",
    "esri/views/MapView",
    "esri/Graphic",
    "esri/layers/GraphicsLayer"
  ], function (Map, MapView, Graphic, GraphicsLayer) {

    const map = new Map({
      basemap: "satellite"
    });

    const overviewMapContainer = document.getElementById("overviewMap");
    if (overviewMapContainer) {
      const view = new MapView({
        container: "overviewMap",
        map: map,
        center: [-98.05, 26.16], // Centered generally over Mercedes and Donna ISD
        zoom: 11
      });

      const pinLayer = new GraphicsLayer();
      map.add(pinLayer);

      // Add pins for all 14 campuses
      projectCampuses.forEach(c => {
        const isReady = c.status === "Active Implementation";

        const pointMarker = {
          type: "simple-marker",
          color: isReady ? [46, 125, 50, 0.9] : [255, 152, 0, 0.8], // Dark Green or Orange
          outline: {
            color: [255, 255, 255],
            width: 2
          },
          size: isReady ? "14px" : "10px"
        };

        const pointGraphic = new Graphic({
          geometry: {
            type: "point",
            longitude: c.coords[0],
            latitude: c.coords[1]
          },
          symbol: pointMarker,
          attributes: c,
          popupTemplate: {
            title: "{name}",
            content: "District: {district}<br>Status: {status}<br>Current Canopy: {canopy.baselinePercent}%<br>Shade Goal: {canopy.targetPercent}%"
          }
        });

        pinLayer.add(pointGraphic);
      });
    }
  });
});

// 3. Selection Logic (Saves to localStorage and redirects)
/**
 * Sets the active campus in localStorage and navigates to its respective dashboard page.
 * @param {string} campusId - The unique identifier of the selected campus.
 */
function selectCampus(campusId) {
  if (!campusId) return;

  const chosen = projectCampuses.find(c => c.id === campusId);
  if (chosen) {
    localStorage.setItem("activeCampusId", chosen.id);
    localStorage.setItem("activeCampusName", chosen.name);
    localStorage.setItem("activeCampusLng", chosen.coords[0]);
    localStorage.setItem("activeCampusLat", chosen.coords[1]);

    // Redirect to the detail page (index.html or the static file)
    window.location.href = campusId + ".html";
  }
}
